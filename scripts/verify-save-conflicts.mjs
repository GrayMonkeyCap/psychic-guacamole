import { TEST_URL } from './verification-config.mjs';
import { createRequire } from 'node:module';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(path.join(process.argv[2], 'package.json'));
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const key = 'system-sandbox:first-level:v2', recovery = 'system-sandbox:first-level:recovery';
const url = `${TEST_URL}/#system-lab`;
const saved = page => page.locator('.l1-save-note').filter({ hasText: 'saved on this device' }).waitFor();
const conflict = page => page.locator('.l1-save-note').filter({ hasText: 'Autosave paused' }).waitFor();
const open = page => page.getByRole('button', { name: 'Save backups & restore' }).click();
const close = page => page.getByRole('button', { name: 'Close save backups' }).click();
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const a = await context.newPage(), b = await context.newPage(), errors = [];
  for (const page of [a, b]) page.on('pageerror', e => errors.push(e.message));
  await a.goto(url);
  await a.getByRole('button', { name: 'Let’s build a link' }).click();
  await a.getByRole('button', { name: 'Add API server', exact: true }).click();
  await saved(a);
  await b.goto(url); await saved(b);
  await a.getByRole('button', { name: 'Add Database', exact: true }).click();
  await saved(a); await conflict(b);
  await b.getByRole('button', { name: 'Add API server', exact: true }).click();
  await conflict(b);
  assert.equal(await b.getByRole('button', { name: /^Inspect API server [12]$/ }).count(), 2);
  assert.equal(await b.evaluate(key => JSON.parse(localStorage.getItem(key)).design.nodes.filter(n => n.type === 'api').length, key), 1);
  await open(b);
  await b.getByRole('button', { name: 'Replace browser save with this board', exact: true }).click();
  await saved(b); await conflict(a);
  assert.equal(await b.evaluate(key => JSON.parse(localStorage.getItem(key)).design.nodes.some(n => n.type === 'database'), recovery), true);
  await close(b);
  await open(a);
  await a.getByRole('button', { name: 'Replace this board with saved copy', exact: true }).click();
  await saved(a); await close(a);
  assert.equal(await a.getByRole('button', { name: /^Inspect API server [12]$/ }).count(), 2);
  assert.equal(await a.getByRole('button', { name: 'Inspect Database', exact: true }).count(), 0);
  assert.equal(await a.evaluate(key => JSON.parse(localStorage.getItem(key)).design.nodes.some(n => n.type === 'database'), recovery), true);
  await a.reload(); await saved(a);
  assert.equal(await a.getByRole('button', { name: /^Inspect API server [12]$/ }).count(), 2);
  // A future format must survive mounting this older build verbatim.
  const future = JSON.stringify({ version: 999, futureBoard: 'preserve me' });
  await b.close();
  await a.evaluate(({ key, future }) => localStorage.setItem(key, future), { key, future });
  await a.reload(); await conflict(a);
  assert.equal(await a.evaluate(key => localStorage.getItem(key), key), future);
  await open(a);
  await a.getByRole('button', { name: 'Replace browser save with this board' }).click();
  await saved(a);
  assert.equal(await a.evaluate(() => localStorage.getItem('system-sandbox:first-level:protected-original')), future);
  await context.close();
  // Denied writes remain explicit; play and file downloads still work.
  const blocked = await browser.newContext();
  await blocked.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('Storage blocked', 'QuotaExceededError'); }; });
  const p = await blocked.newPage();
  p.on('pageerror', e => errors.push(e.message));
  await p.goto(url); await p.getByRole('button', { name: 'Let’s build a link' }).click();
  await p.getByRole('button', { name: 'Add API server', exact: true }).click();
  await p.locator('.l1-save-note').filter({ hasText: 'Unsaved:' }).waitFor();
  await open(p);
  const download = p.waitForEvent('download');
  await p.getByRole('button', { name: 'Download current save' }).click();
  assert.equal((await download).suggestedFilename(), 'system-sandbox-level-1.json');
  assert.deepEqual(errors, []);
  console.log('Save conflict QA passed: concurrent edits, no silent overwrite, explicit choices, displaced-board recovery, reload, future-format protection and denied-write export.');
} finally { await browser.close(); }
