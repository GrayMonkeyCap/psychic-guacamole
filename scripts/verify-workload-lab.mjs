import { TEST_URL } from './verification-config.mjs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { EMPTY_DESIGN, SAVE_KEY, SAVE_VERSION } from '../src/levelModel.js';
const require = createRequire(path.join(process.argv[2], 'package.json'));
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(), errors = [];
  page.setDefaultTimeout(10000);
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${TEST_URL}/#system-lab`);
  await page.getByRole('button', { name: 'Let’s build a link' }).click();
  const trigger = page.getByRole('button', { name: 'Explore traffic mix', exact: true });
  const dialog = page.getByRole('dialog', { name: 'Equal traffic. Different work.' });
  const results = dialog.getByRole('region', { name: 'Workload experiment results', exact: true });
  await trigger.click();
  await dialog.getByRole('button', { name: 'Compare these workloads', exact: true }).click();
  assert.ok((await dialog.innerText()).includes('No experiment was run'));
  assert.equal(await results.count(), 0);
  await page.keyboard.press('Escape');
  assert.ok(await trigger.evaluate(el => el === document.activeElement));

  const design = { nodes: [...EMPTY_DESIGN.nodes, { id: 'api', type: 'api', tier: 1, strategy: 'random', x: 37, y: 43 }, { id: 'db', type: 'database', tier: 1, x: 69, y: 43 }, { id: 'cache', type: 'cache', tier: 0, x: 69, y: 12 }], edges: [{ id: 'a', from: 'internet', to: 'api' }, { id: 'b', from: 'api', to: 'db' }, { id: 'c', from: 'api', to: 'cache' }] };
  await page.evaluate(({ key, save }) => localStorage.setItem(key, JSON.stringify(save)), { key: SAVE_KEY, save: { version: SAVE_VERSION, design, chapter: 0, unlocked: 2, guided: false, history: [], certificates: [], snapshots: [] } });
  await page.reload();
  await page.getByRole('button', { name: 'Send traffic', exact: true }).click();
  assert.ok(await trigger.isDisabled());
  await page.waitForFunction(() => document.querySelectorAll('.l1-bars i').length >= 3);
  await page.getByRole('button', { name: 'Pause traffic', exact: true }).click();
  await page.getByRole('slider', { name: 'Scrub traffic test' }).fill('0');
  const savedBefore = await page.evaluate(key => localStorage.getItem(key), SAVE_KEY);
  const recordingBefore = await page.locator('.l1-bars i').count();
  const sampleBefore = await page.locator('.l1-system-state').innerText();
  await trigger.click();
  const close = dialog.getByRole('button', { name: 'Back to your traffic', exact: true });
  assert.ok(await close.evaluate(el => el === document.activeElement));
  await dialog.getByLabel('Shared peak traffic').selectOption('1000');
  await dialog.getByRole('button', { name: 'Compare these workloads', exact: true }).click();
  await results.waitFor();
  assert.ok((await results.innerText()).includes('No pass or progress awarded'));
  const row = results.getByRole('row').filter({ has: page.getByRole('rowheader', { name: /Database/ }) });
  const cells = await row.getByRole('cell').allTextContents();
  assert.ok(Number(cells[0].split('/')[0]) < Number(cells[1].split('/')[0]), 'Repeated reads reduce this cached design’s database reads.');
  assert.ok((await results.innerText()).includes('850'));
  await dialog.getByRole('button', { name: 'Compare these workloads', exact: true }).focus();
  await page.keyboard.press('Tab');
  const tableRegion = dialog.getByRole('region', { name: 'Workload comparison table; scroll horizontally on small screens', exact: true });
  assert.ok(await tableRegion.evaluate(el => el === document.activeElement));
  await page.keyboard.press('Tab');
  assert.ok(await close.evaluate(el => el === document.activeElement));
  const artifactDir = process.argv[3] || '.test-artifacts/workload-lab';
  await mkdir(artifactDir, { recursive: true });
  await results.scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(artifactDir, 'workload-results.png') });
  for (const width of [768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    await tableRegion.focus();
    await page.keyboard.press('End');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
    assert.ok(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
    assert.ok(await tableRegion.evaluate(el => el.scrollWidth >= el.clientWidth));
  }
  await dialog.getByLabel('Shared peak traffic').selectOption('500');
  assert.equal(await results.count(), 0, 'Changing input clears stale results.');
  await dialog.getByRole('button', { name: 'Compare these workloads', exact: true }).click();
  assert.ok((await results.innerText()).includes('same 500 requests/sec'));
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.l1-bars i').count(), recordingBefore);
  assert.equal(await page.locator('.l1-system-state').innerText(), sampleBefore);
  assert.equal(await page.evaluate(key => localStorage.getItem(key), SAVE_KEY), savedBefore);
  await trigger.click();
  assert.equal(await results.count(), 0, 'Reopening starts a fresh experiment, not stale evidence.');
  await page.keyboard.press('Escape');
  assert.deepEqual(errors, []);
  console.log('Workload lab QA passed: incomplete paths, matched traffic, recorded demand differences, ungraded/read-only behavior, retained paused sample/save, input invalidation, keyboard table/focus and compact layouts.');
} finally { await browser.close(); }
