import { createRequire } from 'node:module';
import path from 'node:path';
import assert from 'node:assert/strict';
import { EMPTY_DESIGN, SAVE_KEY, SAVE_VERSION, CHAPTERS, runChapter } from '../src/levelModel.js';
const require = createRequire(path.join(process.argv[2], 'package.json'));
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5173/');
  const design = { nodes: [...EMPTY_DESIGN.nodes, { id: 'api', type: 'api', tier: 1, strategy: 'random', x: 37, y: 43 }, { id: 'db', type: 'database', tier: 1, x: 69, y: 43 }, { id: 'cache', type: 'cache', tier: 0, x: 69, y: 12 }], edges: [{ id: 'a', from: 'internet', to: 'api' }, { id: 'b', from: 'api', to: 'db' }, { id: 'c', from: 'api', to: 'cache' }] };
  await page.evaluate(({ key, save }) => localStorage.setItem(key, JSON.stringify(save)), { key: SAVE_KEY, save: { version: SAVE_VERSION, design, chapter: 0, unlocked: 2, guided: false, certificates: [], history: [] } });
  await page.goto('http://127.0.0.1:5173/#system-lab');
  await page.getByRole('button', { name: 'Send traffic', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.l1-bars i').length > 0);
  await page.getByRole('button', { name: 'Pause traffic', exact: true }).click();
  await page.getByRole('button', { name: 'System list', exact: true }).click();
  const sampleTime = async () => Number((await page.getByRole('region', { name: 'Text system navigator' }).innerText()).match(/Recorded sample: ([\d.]+)s/)[1]);
  const before = await sampleTime();
  await page.getByRole('button', { name: 'Step 0.2s', exact: true }).click();
  assert.equal(await sampleTime(), Number((before + .2).toFixed(1)));
  await page.getByLabel('Playback speed').selectOption('4');
  const paused = await sampleTime(); await page.waitForTimeout(250);
  assert.equal(await sampleTime(), paused, 'Changing speed must not resume paused traffic.');
  await page.getByRole('button', { name: 'Resume traffic', exact: true }).click();
  // Deterministic visibility-event fixture; no elapsed-time catch-up is allowed.
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')); });
  await page.getByRole('button', { name: 'Resume traffic', exact: true }).waitFor();
  const hidden = await sampleTime(); await page.waitForTimeout(250); assert.equal(await sampleTime(), hidden);
  await page.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event('visibilitychange')); });
  assert.ok(await page.getByRole('button', { name: 'Resume traffic', exact: true }).isVisible());
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Step 0.2s', exact: true }).scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  for (let i = 0; i < 60 && await page.getByRole('button', { name: 'Step 0.2s', exact: true }).count(); i++) await page.getByRole('button', { name: 'Step 0.2s', exact: true }).click();
  const result = page.getByRole('region', { name: 'Traffic test results' });
  assert.ok(await result.evaluate(el => el === document.activeElement), 'Finishing with Step should focus the result.');
  assert.equal(await page.getByRole('slider', { name: 'Scrub traffic test' }).getAttribute('max'), '59');
  const saved = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), SAVE_KEY);
  const check = (actual, expected) => { for (const field of ['maxError', 'estimatedLatencyMs', 'cost', 'passed', 'fingerprint', 'modelVersion', 'scenarioVersion']) assert.deepEqual(actual[field], expected[field], field); };
  check((await saved()).history.at(-1), runChapter(design, CHAPTERS[0]));
  await page.getByLabel('Playback speed').selectOption('2');
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await page.getByRole('button', { name: 'Explain this pass', exact: true }).waitFor({ timeout: 12000 });
  check((await saved()).history.at(-1), runChapter(design, CHAPTERS[0]));
  await page.getByLabel('Playback speed').selectOption('4');
  await page.getByRole('button', { name: 'All three', exact: true }).click();
  await page.getByText('Every challenge, one design.', { exact: true }).waitFor({ timeout: 22000 });
  const suite = (await saved()).history.slice(-3);
  CHAPTERS.forEach((chapter, i) => check(suite[i], runChapter(design, chapter)));
  assert.deepEqual(errors, []);
  console.log('Playback QA passed: exact manual steps, pause/speed separation, visibility fixture, final-step focus, full frame count, 2× equality, 4× cold-start suite equality and mobile controls.');
} finally { await browser.close(); }
