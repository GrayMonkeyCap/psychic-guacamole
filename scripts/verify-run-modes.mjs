import { TEST_URL } from './verification-config.mjs';
import { createRequire } from 'node:module';
import path from 'node:path';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { CHAPTERS, EMPTY_DESIGN, SAVE_KEY, SAVE_VERSION, runChapter } from '../src/levelModel.js';
const require = createRequire(path.join(process.argv[2], 'package.json'));
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const design = { nodes: [...EMPTY_DESIGN.nodes, { id: 'api', type: 'api', tier: 1, strategy: 'random', x: 37, y: 43 }, { id: 'db', type: 'database', tier: 1, x: 69, y: 43 }, { id: 'cache', type: 'cache', tier: 0, x: 69, y: 12 }], edges: [{ id: 'a', from: 'internet', to: 'api' }, { id: 'b', from: 'api', to: 'db' }, { id: 'c', from: 'api', to: 'cache' }] };
  await page.goto(`${TEST_URL}/`);
  await page.evaluate(({ key, save }) => localStorage.setItem(key, JSON.stringify(save)), { key: SAVE_KEY, save: { version: SAVE_VERSION, design, chapter: 0, unlocked: 2, guided: false, history: [], certificates: [] } });
  await page.goto(`${TEST_URL}/#system-lab`);
  const state = page.locator('.l1-system-state');
  const mode = () => state.getAttribute('data-mode');
  const count = () => page.locator('.l1-bars i').count();
  const saved = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), SAVE_KEY);
  assert.equal(await mode(), 'build');
  await page.getByRole('button', { name: 'Send traffic', exact: true }).click();
  assert.equal(await mode(), 'running');
  await page.waitForFunction(() => document.querySelectorAll('.l1-bars i').length >= 4);
  await page.getByRole('button', { name: 'End run', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'End this run and edit?' });
  await dialog.waitFor();
  assert.ok(await page.getByRole('button', { name: 'Keep paused', exact: true }).evaluate(el => el === document.activeElement));
  const pausedCount = await count(); await page.waitForTimeout(350);
  assert.equal(await count(), pausedCount);
  await page.keyboard.press('Escape');
  assert.equal(await dialog.count(), 0);
  assert.equal(await mode(), 'paused');
  assert.ok(await page.getByRole('button', { name: 'End run', exact: true }).evaluate(el => el === document.activeElement));
  assert.ok(await page.getByRole('button', { name: 'Add API server', exact: true }).isDisabled());
  await page.getByRole('button', { name: 'Inspect API server', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  assert.deepEqual((await saved()).design, design, 'Paused keyboard movement cannot change the running design.');
  await page.getByRole('slider', { name: 'Scrub traffic test' }).fill('0');
  assert.ok((await state.innerText()).includes('Paused at 0.2'));
  assert.equal(await count(), pausedCount, 'Scrubbing must not generate traffic.');
  await page.getByRole('button', { name: 'End run', exact: true }).click();
  await page.getByRole('button', { name: 'Keep paused', exact: true }).click();
  assert.equal(await mode(), 'paused');
  await page.getByRole('button', { name: 'End run', exact: true }).click();
  await page.getByRole('button', { name: 'End run & edit', exact: true }).click();
  assert.equal(await mode(), 'partial');
  assert.ok((await state.innerText()).includes('Not graded'));
  assert.equal(await count(), pausedCount);
  assert.equal((await saved()).history.length, 0);
  assert.equal((await saved()).certificates.length, 0);
  assert.equal(await page.getByRole('region', { name: 'Traffic test results' }).count(), 0);
  assert.ok(await page.getByRole('button', { name: 'Try again', exact: true }).evaluate(el => el === document.activeElement));
  const face = page.getByRole('button', { name: 'Inspect API server', exact: true });
  await face.focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await mode(), 'partial'); assert.equal(await count(), pausedCount);
  await page.getByRole('button', { name: 'Undo last edit' }).click();
  await page.getByRole('slider', { name: 'Scrub traffic test' }).fill('0');
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  if (process.argv[3]) { await mkdir(process.argv[3], { recursive: true }); await page.screenshot({ path: path.join(process.argv[3], 'partial-run-mode.png'), fullPage: true }); }
  await page.getByLabel('Playback speed').selectOption('4');
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  assert.equal(await mode(), 'running');
  await page.getByText('CHALLENGE PASSED', { exact: true }).waitFor();
  assert.equal(await mode(), 'review');
  const expected = runChapter(design, CHAPTERS[0]);
  await page.waitForFunction(key => JSON.parse(localStorage.getItem(key)).history.length === 1, SAVE_KEY);
  for (const key of ['maxError', 'estimatedLatencyMs', 'cost', 'passed', 'fingerprint']) assert.equal((await saved()).history[0][key], expected[key]);
  await page.getByRole('button', { name: 'All three', exact: true }).click();
  await page.waitForFunction(key => { const save = JSON.parse(localStorage.getItem(key)); return save.chapter === 1 && save.history.length === 2; }, SAVE_KEY);
  await page.getByRole('button', { name: 'End run', exact: true }).click();
  assert.ok((await dialog.innerText()).includes('remaining challenges'));
  const beforeEnd = await saved();
  await page.getByRole('button', { name: 'End run & edit', exact: true }).click();
  assert.deepEqual((await saved()).certificates, beforeEnd.certificates);
  assert.deepEqual((await saved()).history, beforeEnd.history);
  assert.equal(beforeEnd.certificates.length, 1, 'Ending a suite must not certify unfinished stages.');
  await face.click();
  await page.getByLabel('SHORT CODE STRATEGY').selectOption('sequence');
  assert.equal(await mode(), 'build'); assert.equal(await count(), 0);
  assert.deepEqual((await saved()).certificates, beforeEnd.certificates);
  assert.deepEqual(errors, []);
  console.log('Run-mode QA passed: live/paused/review states, stop confirmation/cancel/focus, locked editing, paused scrubbing, ungraded partial evidence, layout retention, restart equality, suite certificate safety and compact widths.');
} finally { await browser.close(); }
