import { createRequire } from 'node:module';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(path.join(process.argv[2], 'package.json'));
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5173/#system-lab');
  await page.getByRole('button', { name: 'Let’s build a link' }).click();
  await page.getByRole('button', { name: 'Add API server', exact: true }).click();
  await page.getByRole('button', { name: 'Add Database', exact: true }).click();
  await page.getByRole('button', { name: 'Start call from Visitors', exact: true }).click();
  const planner = page.getByRole('region', { name: 'Plan a service call' });
  await planner.getByLabel('Target service').selectOption({ label: 'Database' });
  assert.ok(await planner.getByRole('button', { name: 'Connect this call' }).isDisabled());
  assert.ok((await planner.getByRole('status').innerText()).includes('cannot call'));
  assert.equal(await page.locator('.l1-edge-tag').count(), 0);
  await planner.getByLabel('Target service').selectOption({ label: 'API server' });
  assert.ok((await planner.getByRole('status').innerText()).includes('Do not add a reverse wire'));
  await planner.getByRole('button', { name: 'Connect this call' }).click();
  assert.equal(await page.locator('.l1-edge-tag').count(), 1);
  await page.getByRole('button', { name: 'Start call from API server', exact: true }).click();
  await planner.getByLabel('Target service').selectOption({ label: 'Database' });
  await planner.getByRole('button', { name: 'Connect this call' }).click();
  const api = page.getByRole('button', { name: 'Inspect API server', exact: true });
  await api.click();
  const before = await api.boundingBox();
  await page.getByRole('button', { name: 'Move without dragging' }).click();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button', { name: 'Cancel move' }).count(), 0);
  await page.getByRole('button', { name: 'Move without dragging' }).click();
  const board = await page.locator('.l1-board').boundingBox();
  await page.mouse.click(board.x + board.width * .3, board.y + board.height * .24);
  const moved = await api.boundingBox();
  assert.ok(Math.abs(moved.y - before.y) > 30);
  await page.getByRole('button', { name: 'Undo last edit' }).click();
  assert.ok(Math.abs((await api.boundingBox()).y - before.y) < 1);
  await page.getByRole('button', { name: 'Redo last edit' }).click();
  assert.ok(Math.abs((await api.boundingBox()).y - moved.y) < 1);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('Connection QA passed: invalid preview, request/reply guidance, explicit connect, cancel move, click placement, undo/redo and mobile overflow.');
} finally { await browser.close(); }
