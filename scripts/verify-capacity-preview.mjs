import { TEST_URL } from './verification-config.mjs';
import { createRequire } from 'node:module';
import path from 'node:path';
import assert from 'node:assert/strict';
import { EMPTY_DESIGN, SAVE_KEY, SAVE_VERSION } from '../src/levelModel.js';
const require = createRequire(path.join(process.argv[2], 'package.json'));
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${TEST_URL}/`);
  const design = { nodes: [...EMPTY_DESIGN.nodes, { id: 'api', type: 'api', tier: 0, strategy: 'sequence', x: 37, y: 43 }, { id: 'db', type: 'database', tier: 0, x: 69, y: 43 }], edges: [{ id: 'a', from: 'internet', to: 'api' }, { id: 'b', from: 'api', to: 'db' }] };
  await page.evaluate(({ key, save }) => localStorage.setItem(key, JSON.stringify(save)), { key: SAVE_KEY, save: { version: SAVE_VERSION, design, chapter: 0, unlocked: 0, guided: false, certificates: [], history: [] } });
  await page.goto(`${TEST_URL}/#system-lab`);
  await page.getByRole('button', { name: 'Send traffic', exact: true }).click();
  await page.getByRole('button', { name: 'Inspect API server', exact: true }).click();
  assert.ok(await page.locator('.l1-tiers button').first().isDisabled());
  await page.getByRole('button', { name: 'Explain this pass', exact: true }).waitFor({ timeout: 20000 });
  const baseline = await page.evaluate(key => localStorage.getItem(key), SAVE_KEY);
  const tiers = page.getByRole('group', { name: 'Preview a capacity tier' });
  const preview = page.getByRole('region', { name: 'Proposed capacity change' });
  await tiers.getByRole('button', { name: /Large/ }).click();
  assert.ok((await preview.innerText()).includes('+$235/month'));
  assert.equal(await page.evaluate(key => localStorage.getItem(key), SAVE_KEY), baseline);
  assert.ok(await page.getByRole('slider', { name: 'Scrub traffic test' }).isVisible());
  assert.ok(await page.getByRole('button', { name: 'Undo last edit' }).isDisabled());
  await page.getByRole('button', { name: 'Cancel tier preview' }).click();
  assert.equal(await preview.count(), 0);
  await tiers.getByRole('button', { name: /Large/ }).click();
  await page.getByRole('button', { name: 'Apply Large tier', exact: true }).click();
  await page.waitForFunction(key => JSON.parse(localStorage.getItem(key)).design.nodes.find(n => n.id === 'api').tier === 2, SAVE_KEY);
  assert.equal(await page.getByRole('slider', { name: 'Scrub traffic test' }).count(), 0);
  await page.getByRole('button', { name: 'Undo last edit' }).click();
  await page.waitForFunction(key => JSON.parse(localStorage.getItem(key)).design.nodes.find(n => n.id === 'api').tier === 0, SAVE_KEY);
  assert.ok(await page.getByRole('button', { name: 'First link · Passed for this design', exact: true }).isVisible());
  await page.getByRole('button', { name: 'Redo last edit' }).click();
  await page.getByRole('button', { name: 'Show all tools' }).click();
  await page.getByRole('button', { name: 'Add Edge cache', exact: true }).click();
  await page.getByRole('button', { name: 'Inspect Database', exact: true }).click();
  await tiers.getByRole('button', { name: /Large/ }).click();
  assert.ok((await preview.innerText()).includes('$960 / $900'));
  assert.ok((await preview.innerText()).includes('$60 over budget'));
  assert.ok(await preview.getByRole('rowheader', { name: 'All-write ceiling /s' }).isVisible());
  await page.setViewportSize({ width: 390, height: 844 });
  await preview.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
  assert.deepEqual(errors, []);
  console.log('Capacity preview QA passed: disabled during run, explicit cost deltas, preview/cancel preserve recording and save, apply/undo/redo, shared storage limits, budget warning and compact width.');
} finally { await browser.close(); }
