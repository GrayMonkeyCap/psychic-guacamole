import { createRequire } from 'node:module';
import path from 'node:path';
import assert from 'node:assert/strict';
import { SAVE_KEY, SAVE_VERSION } from '../src/levelModel.js';
const require = createRequire(path.join(process.argv[2], 'package.json'));
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5173/');
  const design = { nodes: [{ id: 'internet', type: 'internet', tier: 0, x: 7, y: 43 }, { id: 'api', type: 'api', tier: 0, strategy: 'sequence', x: 37, y: 43 }, { id: 'db', type: 'database', tier: 0, x: 69, y: 43 }], edges: [{ id: 'a', from: 'internet', to: 'api' }, { id: 'b', from: 'api', to: 'db' }] };
  await page.evaluate(({ key, save }) => localStorage.setItem(key, JSON.stringify(save)), { key: SAVE_KEY, save: { version: SAVE_VERSION, design, chapter: 0, unlocked: 0, guided: false, certificates: [], history: [] } });
  await page.goto('http://127.0.0.1:5173/#system-lab');
  const api = page.getByRole('button', { name: 'Inspect API server', exact: true });
  await page.getByRole('button', { name: 'Send traffic', exact: true }).click();
  await page.getByText('CHALLENGE PASSED', { exact: true }).waitFor({ timeout: 18000 });
  const before = await api.boundingBox();
  await api.focus(); await page.keyboard.press('ArrowRight');
  assert.ok((await api.boundingBox()).x > before.x + 5);
  await page.getByRole('slider', { name: 'Scrub traffic test' }).fill('2');
  await page.keyboard.press('Control+z'); // input focus should not undo the graph
  assert.ok((await api.boundingBox()).x > before.x + 5);
  await page.getByRole('button', { name: 'Undo last edit' }).click();
  assert.ok(Math.abs((await api.boundingBox()).x - before.x) < 1);
  assert.equal(await page.getByRole('slider', { name: 'Scrub traffic test' }).inputValue(), '2');
  await page.keyboard.press('Control+Shift+z');
  assert.ok((await api.boundingBox()).x > before.x + 5);
  assert.ok(await page.getByText('CHALLENGE PASSED', { exact: true }).isVisible());
  await api.click();
  await page.getByLabel('SHORT CODE STRATEGY').focus(); await page.keyboard.press('Delete');
  assert.equal(await api.count(), 1);
  await page.getByRole('button', { name: 'How this component works' }).focus(); await page.keyboard.press('Delete');
  assert.equal(await api.count(), 1);
  await api.focus(); await page.keyboard.press('Delete');
  assert.equal(await api.count(), 0);
  assert.equal(await page.getByText('CHALLENGE PASSED', { exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Undo last edit' }).click();
  assert.equal(await api.count(), 1);
  await page.keyboard.press('Control+y');
  assert.equal(await api.count(), 0);
  await page.getByRole('button', { name: 'Undo last edit' }).click();
  await api.focus(); await page.keyboard.press('ArrowDown');
  assert.ok(await page.getByRole('button', { name: 'Redo last edit' }).isDisabled());
  const position = await api.boundingBox();
  await page.mouse.move(position.x + 45, position.y + 25); await page.mouse.down();
  await page.mouse.move(position.x + 85, position.y + 65, { steps: 5 }); await page.mouse.up();
  await page.getByRole('button', { name: 'Undo last edit' }).click();
  assert.ok(Math.abs((await api.boundingBox()).x - position.x) < 1);
  await page.getByRole('button', { name: 'Redo last edit' }).click();
  assert.ok((await api.boundingBox()).x > position.x + 30);
  assert.deepEqual(errors, []);
  console.log('Edit history QA passed: geometry evidence, undo/redo buttons and shortcuts, scoped deletion, no text-control interception, redo branching, one drag per history step.');
} finally { await browser.close(); }
