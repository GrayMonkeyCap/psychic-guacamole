import { TEST_URL } from './verification-config.mjs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { CATALOG, EMPTY_DESIGN, SAVE_KEY, SAVE_VERSION } from '../src/levelModel.js';
const require = createRequire(path.join(process.argv[2], 'package.json'));
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(), errors = [];
  page.setDefaultTimeout(10000);
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${TEST_URL}/#system-lab`);
  await page.getByRole('button', { name: 'Let’s build a link' }).click();
  const trigger = page.getByRole('button', { name: 'Help me choose', exact: true });
  await trigger.focus(); await page.keyboard.press('Enter');
  const dialog = page.getByRole('dialog', { name: 'What job needs doing?' });
  const choices = dialog.getByRole('button', { name: 'Back to building', exact: true });
  await choices.waitFor();
  assert.ok(await choices.evaluate(el => el === document.activeElement));
  await page.keyboard.press('Shift+Tab');
  assert.ok(await dialog.locator('.l1-learning-resources summary').evaluate(el => el === document.activeElement), 'Closed disclosures must not trap focus on invisible links.');
  await page.keyboard.press('Tab');
  assert.ok(await choices.evaluate(el => el === document.activeElement));
  for (const config of Object.values(CATALOG)) {
    await dialog.getByRole('button', { name: `${config.name} ${config.verb}`, exact: true }).click();
    assert.ok((await dialog.innerText()).includes('Forecast only'));
    assert.equal(await page.locator('.l1-node').count(), 1, 'Reading choices never places components.');
  }
  await dialog.getByRole('button', { name: 'Memory cache Remembers popular reads', exact: true }).click();
  await dialog.locator('.l1-learning-resources summary').click();
  const link = dialog.getByRole('link', { name: /AWS · Cache-aside pattern/ });
  const href = await link.getAttribute('href');
  await context.route(href, route => route.fulfill({ contentType: 'text/html', body: '<title>Documentation navigation fixture</title>' }));
  const popupPromise = context.waitForEvent('page');
  await link.click();
  const popup = await popupPromise; await popup.waitForLoadState();
  assert.equal(popup.url(), href);
  assert.equal(await popup.evaluate(() => window.opener), null);
  await popup.close();
  assert.equal(page.url(), `${TEST_URL}/#system-lab`);
  assert.equal(await page.locator('.l1-node').count(), 1);
  const artifactDir = process.argv[3] || '.test-artifacts/component-choices';
  await mkdir(artifactDir, { recursive: true });
  await page.screenshot({ path: path.join(artifactDir, 'component-choices-desktop.png') });
  for (const width of [768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    await dialog.getByRole('button', { name: 'Place Memory cache', exact: true }).scrollIntoViewIfNeeded();
    assert.ok((await dialog.getByRole('button', { name: 'Place Memory cache', exact: true }).boundingBox()).y < 900);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
    assert.ok(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  }
  await page.keyboard.press('Escape');
  assert.equal(await dialog.count(), 0);
  assert.ok(await trigger.evaluate(el => el === document.activeElement));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await trigger.click();
  await dialog.getByRole('button', { name: 'Place API server', exact: true }).click();
  assert.equal(await page.locator('.l1-node').count(), 2);
  await page.getByRole('button', { name: 'Undo last edit', exact: true }).click();
  assert.equal(await page.locator('.l1-node').count(), 1);

  const design = { nodes: [...EMPTY_DESIGN.nodes, { id: 'api', type: 'api', tier: 0, strategy: 'random', x: 37, y: 43 }, { id: 'db', type: 'database', tier: 0, x: 69, y: 43 }], edges: [{ id: 'a', from: 'internet', to: 'api' }, { id: 'b', from: 'api', to: 'db' }] };
  await page.evaluate(({ key, save }) => localStorage.setItem(key, JSON.stringify(save)), { key: SAVE_KEY, save: { version: SAVE_VERSION, design, chapter: 1, unlocked: 2, guided: false, history: [], certificates: [], snapshots: [] } });
  await page.reload();
  await page.getByRole('button', { name: 'Inspect API server', exact: true }).click();
  const advice = page.locator('.l1-inspector .l1-choice-advice');
  assert.ok((await advice.innerText()).includes('Forecast only'));
  await page.getByRole('button', { name: 'Send traffic', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.l1-bars i').length >= 3);
  await page.getByRole('button', { name: 'Pause traffic', exact: true }).click();
  await page.getByRole('slider', { name: 'Scrub traffic test' }).fill('0');
  assert.ok((await advice.innerText()).includes('Recorded sample 0.2s'));
  await trigger.click();
  assert.ok(await dialog.getByRole('button', { name: 'Place API server', exact: true }).isDisabled());
  await dialog.getByRole('button', { name: 'Memory cache Remembers popular reads', exact: true }).click();
  assert.ok((await dialog.innerText()).includes('98%'));
  assert.ok((await dialog.innerText()).includes('No work recorded'));
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'End run', exact: true }).click();
  await page.getByRole('button', { name: 'End run & edit', exact: true }).click();
  await page.getByRole('button', { name: /Opening day ·/ }).click();
  await trigger.click();
  await dialog.getByRole('button', { name: 'Memory cache Remembers popular reads', exact: true }).click();
  assert.ok((await dialog.innerText()).includes('85%'));
  assert.ok((await dialog.innerText()).includes('cannot save these writes'));
  assert.ok((await dialog.innerText()).includes('Forecast only'));
  assert.deepEqual(errors, []);
  console.log('Component choice QA passed: six previews, no automatic placement, safe external navigation, keyboard focus, compact layouts, undo, recorded scrub evidence, paused edit lock and live workload context.');
} finally { await browser.close(); }
